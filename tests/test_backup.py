import importlib.util
import json
import os
from pathlib import Path
import sqlite3
import stat
import tempfile
import threading
import time
import unittest

SPEC = importlib.util.spec_from_file_location('fanntv_backup', Path(__file__).parents[1] / 'scripts' / 'backup.py')
backup = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(backup)


class BackupTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.database = self.root / 'live.sqlite3'
        self.output = self.root / 'backups'
        with sqlite3.connect(self.database) as db:
            db.execute('CREATE TABLE items(id INTEGER PRIMARY KEY, value TEXT)')
            db.execute("INSERT INTO items(value) VALUES('existing')")

    def tearDown(self):
        self.temp.cleanup()

    def test_snapshot_is_consistent_and_restorable_with_live_writes(self):
        stop = threading.Event()
        errors = []

        def writer():
            try:
                with sqlite3.connect(self.database) as db:
                    db.execute('PRAGMA journal_mode=WAL')
                    while not stop.is_set():
                        db.execute("INSERT INTO items(value) VALUES('concurrent')")
                        db.commit()
                        time.sleep(0.001)
            except Exception as error:
                errors.append(error)

        thread = threading.Thread(target=writer)
        thread.start()
        try:
            metadata = backup.create_backup(self.database, self.output)
        finally:
            stop.set()
            thread.join(5)
        self.assertFalse(thread.is_alive())
        self.assertEqual(errors, [])
        self.assertTrue(metadata['restore_verified'])
        snapshot = self.output / metadata['file']
        self.assertEqual(backup.digest(snapshot), metadata['sha256'])
        with sqlite3.connect(snapshot) as db:
            backup.integrity_check(db)
            self.assertGreaterEqual(db.execute('SELECT COUNT(*) FROM items').fetchone()[0], 1)
            self.assertEqual(db.execute('SELECT value FROM items WHERE id=1').fetchone()[0], 'existing')
        self.assertEqual(stat.S_IMODE(snapshot.stat().st_mode), 0o600)
        self.assertEqual(stat.S_IMODE(snapshot.with_suffix('.sqlite3.json').stat().st_mode), 0o600)
        self.assertEqual(stat.S_IMODE(self.output.stat().st_mode), 0o700)

    def test_retention_does_not_delete_unmanaged_databases(self):
        metadata = backup.create_backup(self.database, self.output, retain=2)
        unmanaged = self.output / 'customer.sqlite3'
        unmanaged.write_bytes(b'user data')
        forged_name = self.output / 'fanntv-20000101T000000000000Z-0123abcd.sqlite3'
        forged_name.write_bytes(b'not generated by this utility')
        for _ in range(3):
            backup.create_backup(self.database, self.output, retain=2)
        self.assertFalse((self.output / metadata['file']).exists())
        self.assertEqual(len(list(self.output.glob('*.sqlite3.json'))), 2)
        self.assertEqual(unmanaged.read_bytes(), b'user data')
        self.assertTrue(forged_name.exists())
        self.assertTrue(self.database.exists())

    def test_corruption_or_untrusted_metadata_never_qualifies_for_pruning(self):
        metadata = backup.create_backup(self.database, self.output)
        snapshot = self.output / metadata['file']
        snapshot.write_bytes(b'tampered')
        for _ in range(2):
            backup.create_backup(self.database, self.output, retain=1)
        self.assertTrue(snapshot.exists())

    def test_foreign_metadata_is_never_pruned(self):
        metadata = backup.create_backup(self.database, self.output)
        snapshot = self.output / metadata['file']
        snapshot.with_suffix('.sqlite3.json').write_text('["foreign", "metadata"]')
        backup.create_backup(self.database, self.output, retain=1)
        self.assertTrue(snapshot.exists())

    def test_invalid_database_fails_without_published_backup(self):
        self.database.write_bytes(b'not a sqlite database')
        with self.assertRaises(sqlite3.DatabaseError):
            backup.create_backup(self.database, self.output)
        self.assertEqual(list(self.output.iterdir()), [])

    def test_missing_database_is_not_created(self):
        missing = self.root / 'missing.sqlite3'
        with self.assertRaises(FileNotFoundError):
            backup.create_backup(missing, self.output)
        self.assertFalse(missing.exists())

    def test_shared_backup_directory_is_rejected(self):
        self.output.mkdir(mode=0o755)
        self.output.chmod(0o755)
        with self.assertRaises(PermissionError):
            backup.create_backup(self.database, self.output)

    def test_invalid_retention_is_rejected(self):
        with self.assertRaises(ValueError):
            backup.create_backup(self.database, self.output, retain=0)


if __name__ == '__main__':
    unittest.main()
